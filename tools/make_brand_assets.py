#!/usr/bin/env python3
"""Generates every Codex Ciné brand asset from one geometry (requires Pillow and fontTools).

    pip install pillow fonttools
    python3 tools/make_brand_assets.py

The mark is a film strip bent into a C around a play triangle. Its perforations are cut out of the
strip (even-odd fill), so the mark works on any background. The wordmark is set in Space Grotesk Bold,
converted to outlines so that it needs no font at runtime.
"""
import math
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"
DISPLAY_FONT = RES / "font/space_grotesk_bold.ttf"

NIGHT = "#0B0D1A"
INK = "#1B1F3B"
AMBER = "#F5A623"
IVORY = "#F4EFE6"

# Mark geometry, in a 200 x 200 box centred on (100, 100).
CENTER = 100.0
STRIP_RADIUS = 60.0
STRIP_HALF_WIDTH = 17.0
OPENING_DEG = 40.0  # The C opens to the right, between -40° and +40°.
HOLE_LENGTH, HOLE_GAP, HOLE_WIDTH = 5.0, 7.0, 6.0
HOLE_RADII = (48.5, 71.5)
TRIANGLE = [(86.0, 78.0), (124.0, 100.0), (86.0, 122.0)]


def polar(radius, degrees, cx=CENTER, cy=CENTER):
    angle = math.radians(degrees)
    return cx + radius * math.cos(angle), cy + radius * math.sin(angle)


def fmt(value):
    return f"{value:.2f}".rstrip("0").rstrip(".")


def holes():
    """Perforations along both edges of the strip, as quadrilaterals."""
    shapes = []
    for radius in HOLE_RADII:
        period = math.degrees((HOLE_LENGTH + HOLE_GAP) / radius)
        length = math.degrees(HOLE_LENGTH / radius)
        start, end = OPENING_DEG, 360.0 - OPENING_DEG
        count = int((end - start - length) // period) + 1
        offset = start + ((end - start) - ((count - 1) * period + length)) / 2
        for index in range(count):
            a0 = offset + index * period
            a1 = a0 + length
            inner, outer = radius - HOLE_WIDTH / 2, radius + HOLE_WIDTH / 2
            shapes.append([polar(inner, a0), polar(outer, a0), polar(outer, a1), polar(inner, a1)])
    return shapes


def strip_path():
    outer, inner = STRIP_RADIUS + STRIP_HALF_WIDTH, STRIP_RADIUS - STRIP_HALF_WIDTH
    o0, o1 = polar(outer, OPENING_DEG), polar(outer, -OPENING_DEG)
    i1, i0 = polar(inner, -OPENING_DEG), polar(inner, OPENING_DEG)
    parts = [
        f"M{fmt(o0[0])},{fmt(o0[1])}A{fmt(outer)},{fmt(outer)} 0 1,1 {fmt(o1[0])},{fmt(o1[1])}"
        f"L{fmt(i1[0])},{fmt(i1[1])}A{fmt(inner)},{fmt(inner)} 0 1,0 {fmt(i0[0])},{fmt(i0[1])}Z"
    ]
    for quad in holes():
        parts.append("M" + "L".join(f"{fmt(x)},{fmt(y)}" for x, y in quad) + "Z")
    return "".join(parts)


def triangle_path():
    return "M" + "L".join(f"{fmt(x)},{fmt(y)}" for x, y in TRIANGLE) + "Z"


def text_path(font, text, x, baseline, size):
    """Outlines of [text] at [size] (pixels per em), starting at [x] on [baseline]. Returns (path, end x)."""
    scale = size / font["head"].unitsPerEm
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    metrics = font["hmtx"]
    pen = SVGPathPen(glyph_set, ntos=fmt)
    for char in text:
        name = cmap[ord(char)]
        glyph_set[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, baseline)))
        x += metrics[name][0] * scale
    return pen.getCommands(), x


def vector(path, width_dp, height_dp, viewport_w, viewport_h, groups, lint_ignore=None):
    body = "\n".join(groups)
    tools = (
        f'\n    xmlns:tools="http://schemas.android.com/tools"\n    tools:ignore="{lint_ignore}"' if lint_ignore else ""
    )
    path.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/make_brand_assets.py. Edit the script, not this file. -->\n"
        f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{tools}\n'
        f'    android:width="{width_dp}dp"\n    android:height="{height_dp}dp"\n'
        f'    android:viewportWidth="{fmt(viewport_w)}"\n    android:viewportHeight="{fmt(viewport_h)}">\n'
        f"{body}\n</vector>\n"
    )


def path_xml(data, color, even_odd=False, indent="    "):
    fill_type = f'\n{indent}    android:fillType="evenOdd"' if even_odd else ""
    return (
        f"{indent}<path\n{indent}    android:fillColor=\"{color}\"{fill_type}\n"
        f'{indent}    android:pathData="{data}" />'
    )


def mark_group(scale, dx, dy):
    return (
        f'    <group\n        android:scaleX="{fmt(scale)}"\n        android:scaleY="{fmt(scale)}"\n'
        f'        android:translateX="{fmt(dx)}"\n        android:translateY="{fmt(dy)}">\n'
        + path_xml(strip_path(), AMBER, even_odd=True, indent="        ")
        + "\n"
        + path_xml(triangle_path(), IVORY, indent="        ")
        + "\n    </group>"
    )


def write_vectors(font):
    drawable = RES / "drawable"
    # The mark alone.
    vector(drawable / "ic_logo_mark.xml", 120, 120, 200, 200, [mark_group(1, 0, 0)])

    # Horizontal lockup: mark, then the wordmark, its cap height half the mark's height.
    cap_height = font["OS/2"].sCapHeight / font["head"].unitsPerEm
    size = 52 / cap_height
    baseline = 100 + 26
    codex, x = text_path(font, "Codex ", 212, baseline, size)
    cine, end = text_path(font, "Ciné", x, baseline, size)
    width = end + 8
    vector(
        drawable / "logo_lockup.xml", round(width * 48 / 200), 48, width, 200,
        [mark_group(1, 0, 0), path_xml(codex, IVORY), path_xml(cine, AMBER)],
    )

    # Adaptive launcher icon foreground: 108 dp, keep the art inside the 66 dp safe circle.
    vector(drawable / "ic_launcher_foreground.xml", 108, 108, 108, 108, [mark_group(0.3, 24, 24)])

    # Splash icon: 288 dp without a background; the art must fit a 192 dp circle.
    # 288 dp is the size the splash screen API requires, over lint's 200 dp advice for vectors.
    vector(drawable / "splash_icon.xml", 288, 288, 288, 288, [mark_group(0.82, 62, 62)], lint_ignore="VectorRaster")


def write_banner(font_path):
    """The Android TV banner, 320 x 180 at xhdpi, drawn 4x larger and scaled down for anti-aliasing."""
    from PIL import ImageFont

    k = 4
    width, height = 320 * k, 180 * k
    image = Image.new("RGB", (width, height), INK)
    draw = ImageDraw.Draw(image)

    mark_size = 112 * k
    left = 22 * k
    top = (height - mark_size) / 2
    unit = mark_size / 200

    def to_px(point):
        return left + point[0] * unit, top + point[1] * unit

    outer, inner = STRIP_RADIUS + STRIP_HALF_WIDTH, STRIP_RADIUS - STRIP_HALF_WIDTH
    steps = 240
    angles = [OPENING_DEG + (360 - 2 * OPENING_DEG) * i / steps for i in range(steps + 1)]
    band = [to_px(polar(outer, a)) for a in angles] + [to_px(polar(inner, a)) for a in reversed(angles)]
    draw.polygon(band, fill=AMBER)
    for quad in holes():
        draw.polygon([to_px(p) for p in quad], fill=INK)
    draw.polygon([to_px(p) for p in TRIANGLE], fill=IVORY)

    font = ImageFont.truetype(str(font_path), 46 * k)
    text_left = left + mark_size + 10 * k
    line_height = 44 * k
    first_top = height / 2 - line_height
    draw.text((text_left, first_top), "Codex", font=font, fill=IVORY)
    draw.text((text_left, first_top + line_height), "Ciné", font=font, fill=AMBER)

    out = RES / "drawable-xhdpi/banner.png"
    image.resize((320, 180), Image.LANCZOS).save(out, optimize=True)


def main():
    font = TTFont(DISPLAY_FONT)
    write_vectors(font)
    write_banner(DISPLAY_FONT)
    print("Brand assets written to", RES)


if __name__ == "__main__":
    main()
